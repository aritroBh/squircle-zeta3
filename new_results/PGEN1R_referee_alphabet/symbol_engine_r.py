def cross_ratios(pts4, idx, s):
    """the 6 cross-ratio values of a 4-subset, each as (vec of cr, vec of 1-cr)."""
    a,b,c,d = pts4
    out = []
    import itertools
    seen = set()
    for (w,x,y,z) in [(a,b,c,d),(a,b,d,c),(a,c,b,d),(a,c,d,b),(a,d,b,c),(a,d,c,b)]:
        st, cr = ratio_vec([diff_vec(w,y,idx,s), diff_vec(x,z,idx,s)],
                           [diff_vec(w,z,idx,s), diff_vec(x,y,idx,s)])
        assert st=='OK', (pts4,(w,x,y,z),st)
        st2, oc = ratio_vec([diff_vec(w,x,idx,s), diff_vec(y,z,idx,s)],
                            [diff_vec(w,z,idx,s), diff_vec(x,y,idx,s)])
        assert st2=='OK'
        key = tuple(sorted(cr.items()))
        if key not in seen:
            seen.add(key)
            out.append((cr, oc))
    return out

def li3_symbol(cr_vec, one_minus):
    """S(Li3(z)) = z (x) z (x) (1-z)."""
    out = {}
    for i,ei in cr_vec.items():
        for j,ej in cr_vec.items():
            for k,ek in one_minus.items():
                out[(i,j,k)] = out.get((i,j,k),0)+ei*ej*ek
                if out[(i,j,k)]==0: del out[(i,j,k)]
    return out

# ---- Lyndon basis of Lie^3 and the pairing ----
def lyndon3(n):
    ws = []
    for i in range(n):
        for j in range(n):
            for k in range(n):
                w = (i,j,k)
                if w < (j,k,i) and w < (k,i,j):
                    ws.append(w)
    return ws

def bracket_tensor(w):
    i,j,k = w
    out = {}
    if j < k:   # [e_i,[e_j,e_k]] = ijk - ikj - jki + kji
        terms = [((i,j,k),1), ((i,k,j),-1), ((j,k,i),-1), ((k,j,i),1)]
    else:       # [[e_i,e_j],e_k] = ijk - jik - kij + kji
        terms = [((i,j,k),1), ((j,i,k),-1), ((k,i,j),-1), ((k,j,i),1)]
    for key,c in terms:
        out[key] = out.get(key,0)+c
        if out[key]==0: del out[key]
    return out

def pairing_row(T, B):
    return [sum(T.get(key,0)*cf for key,cf in b.items()) for b in B]

def shuffle_D(n):
    """generators of D: sh(x; y,z) = xyz + yxz + yzx for all ordered triples."""
    gens = []
    for x in range(n):
        for y in range(n):
            for z in range(n):
                g = {}
                for key in [(x,y,z),(y,x,z),(y,z,x)]:
                    g[key] = g.get(key,0)+1
                gens.append({k:c for k,c in g.items() if c})
    return gens

def words_dc(A, s):
    """convergent distinct-letter words over alphabet A = list of points."""
    out = []
    for w in __import__('itertools').permutations(A, 3):
        if w[0]!=('0',) and w[2]!=('1',):
            out.append(w)
    return out
