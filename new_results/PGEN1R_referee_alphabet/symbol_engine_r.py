def letters(s):
    """letter list: p_1..p_s, 1-p_1..1-p_s, p_i-p_j (i<j). Returns (list, index dict)."""
    L = [('p',i) for i in range(s)] + [('q',i) for i in range(s)] + [('r',i,j) for i in range(s) for j in range(i+1,s)]
    return L, {nm:k for k,nm in enumerate(L)}

# points: ('0',), ('1',), ('inf',), ('p',i)
def diff_vec(a, b, idx, s):
    """letter vector of (a-b), signs dropped. Returns dict, or 'INF' for inf-differences."""
    if a == b: return None
    if a == ('inf',) or b == ('inf',): return 'INF'
    za = a[0] == '0'; oa = a[0] == '1'
    zb = b[0] == '0'; ob = b[0] == '1'
    if (za and ob) or (oa and zb): return {}          # +-1 torsion
    if a[0]=='p' and b[0]=='p':
        i,j = a[1], b[1]
        if i<j: return {idx[('r',i,j)]: 1}
        else:   return {idx[('r',j,i)]: 1}
    if a[0]=='p' and zb: return {idx[('p',a[1])]: 1}
    if za and b[0]=='p': return {idx[('p',b[1])]: 1}
    if a[0]=='p' and ob: return {idx[('q',a[1])]: 1}
    if oa and b[0]=='p': return {idx[('q',b[1])]: 1}
    raise ValueError((a,b))

def vadd(u, v, sg=1):
    out = dict(u)
    for k,c in v.items():
        out[k] = out.get(k,0)+sg*c
        if out[k]==0: del out[k]
    return out

def ratio_vec(num_ds, den_ds):
    """(product of num differences)/(product of den differences) as letter vector.
    Handles INF factors (must cancel). Returns ('TORSION',None) if ratio=+-1,
    ('ZERO',None) if ratio 0/inf, else ('OK', vec)."""
    inf = 0; vec = {}
    for d in num_ds:
        if d == 'INF': inf += 1
        elif d is None: return ('ZERO', None)
        else: vec = vadd(vec, d)
    for d in den_ds:
        if d == 'INF': inf -= 1
        elif d is None: return ('ZERO', None)
        else: vec = vadd(vec, d, -1)
    if inf != 0: return ('ZERO', None)
    if not vec: return ('TORSION', None)
    return ('OK', vec)

def s1_vec(x, idx, s):
    """symbol of I(0;x;1) = log((1-x)/(-x)): letters (1-x) - (x). x in {1,p_i} or (formally) 0."""
    if x == ('0',): return {'ZERO': -1}         # log(1/-0): formal
    if x == ('1',): return {'ZERO': 1}          # log(0/-1): formal
    return vadd({idx[('q',x[1])]:1}, {idx[('p',x[1])]:1}, -1)

def tmul(T, vec):
    """append a last tensor factor (letter vector). T: dict (i,j,k)->c ; vec dict l->e."""
    out = {}
    for (i,j,k),c in T.items():
        for l,e in vec.items():
            key = (i,j,l)
            out[key] = out.get(key,0)+c*e
            if out[key]==0: del out[key]
    return out

def tadd(*Ts):
    out = {}
    for T in Ts:
        for k,c in T.items():
            out[k] = out.get(k,0)+c
            if out[k]==0: del out[k]
    return out

def S2(x, y, idx, s):
    """symbol of I(0;x,y;1): S1(y) x [(y-x)/x] + S1(x) x [(1-y)/(y-x)]; torsion ratios dropped."""
    terms = []
    st, rv = ratio_vec([diff_vec(y,x,idx,s)],[diff_vec(x,('0',),idx,s)])
    if st=='OK': terms.append(tmul({(k,):c for k,c in s1_vec(y,idx,s).items()}, rv))
    st, rv = ratio_vec([diff_vec(('1',),y,idx,s)],[diff_vec(y,x,idx,s)])
    if st=='OK': terms.append(tmul({(k,):c for k,c in s1_vec(x,idx,s).items()}, rv))
    return tadd(*terms) if terms else {}

def S2_pair(x, y, idx, s):
    """S2 with 2-tensor keys (i,j)."""
    out = {}
    st, rv = ratio_vec([diff_vec(y,x,idx,s)],[diff_vec(x,('0',),idx,s)])
    if st=='OK':
        for k,c in s1_vec(y,idx,s).items():
            for l,e in rv.items():
                out[(k,l)] = out.get((k,l),0)+c*e
                if out[(k,l)]==0: del out[(k,l)]
    st, rv = ratio_vec([diff_vec(('1',),y,idx,s)],[diff_vec(y,x,idx,s)])
    if st=='OK':
        for k,c in s1_vec(x,idx,s).items():
            for l,e in rv.items():
                out[(k,l)] = out.get((k,l),0)+c*e
                if out[(k,l)]==0: del out[(k,l)]
    return out

