
"""PGEN1R: independent symbol engine for claim A.
Letters on an edge: points {0,1,p_1..p_s} (formal p_j); letter group generated by
p_i, 1-p_i, p_i-p_j (signs/torsion dropped, tensors over Q).
Symbols: sparse integer dicts {(i,j,k): coeff} over letter indices.
Quotient Q3 = tensor^3 / D, D = shuffle decomposables; computed via the
PERFECT pairing with Lie^3 (Lyndon bracket words): shuffles pair to zero with
primitives (standard Hopf fact), and dims match by Witt.
"""
