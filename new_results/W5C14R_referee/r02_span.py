"""r02: independent span test mod p, in the two sectors of complex conjugation (u = 7).
Usage: r02_span.py p sector(+|-)
Generator set Lgen = std rows (W5C1 data) + all lift rows regenerated by me (r02a), and implicitly their u=7 images
(sector projection). Claim tested, for every one of the 74 targets:
    x_t = u.f_i - sum_j a_j F_j   in   span(Lgen u 7.Lgen) + e sh span(G u 7.G)
with a_j from W5G2's cert_summary.pkl, F_j = frame rows (validated_w5 data; frame234 lifts regenerated by me),
G = A3h5's 5042 base rows T0[S] + weight-4 lifts (own shuffle) of the 13 A3h4 frame rows named in W5G2 t05/t06.
Method: M' = random sparse combinations of the projected generator rows (so rowspace(M') is inside the span: a
membership found is sound; randomness can only cause false negatives), own dense elimination (relim.py) with the test
rows carried along; then membership in rowspace + e sh G is decided on the residues."""
from rc import *
import scipy.sparse as sps
from relim import elim, inv_small
p = int(sys.argv[1]); SEC = sys.argv[2]
LOG = f'r02_{p}_{"p" if SEC == "+" else "m"}.log'
t0 = time.time()
rng = np.random.default_rng(p + (1 if SEC == '+' else 2))
W5 = WORDS(5); ID5 = {w: i for i, w in enumerate(W5)}; N5 = len(W5)
W4 = WORDS(4)
def modq(c):
    c = F(c); return (c.numerator % p) * pow(c.denominator % p, p - 2, p) % p
# ---- sector projection (own) ----
sig = np.array([ID5[act(w, 7)] for w in W5])
reps = [i for i in range(N5) if sig[i] >= i]
fixed = [i for i in range(N5) if sig[i] == i]
if SEC == '+':
    cols = reps
    Pr, Pc, Pv = [], [], []
    for k, i in enumerate(cols):
        Pr.append(i); Pc.append(k); Pv.append(1)
        if sig[i] != i: Pr.append(sig[i]); Pc.append(k); Pv.append(1)
else:
    cols = [i for i in reps if sig[i] != i]
    Pr, Pc, Pv = [], [], []
    for k, i in enumerate(cols):
        Pr += [i, sig[i]]; Pc += [k, k]; Pv += [1, -1]
n = len(cols)
Pm = sps.csr_matrix((np.array(Pv, np.int64), (Pr, Pc)), shape=(N5, n))
log(f'p={p} sector {SEC}: dim {n} (fixed words {len(fixed)})', LOG)
def to_csr(dicts):
    r, c, v = [], [], []
    for a, d in enumerate(dicts):
        for w, x in d.items():
            r.append(a); c.append(ID5[w]); v.append(modq(x))
    M = sps.csr_matrix((np.array(v, np.int64), (r, c)), shape=(len(dicts), N5))
    M = (M @ Pm); M.data %= p; M.eliminate_zeros()
    return M
def dense(M):
    D = M.toarray().astype(np.float64); np.mod(D, p, out=D); return D
# ---- generators ----
gens = [d for _, d in load_rows('std')]
mine = pickle.load(open(HERE + '/my_lifts.pkl', 'rb'))
for fam in ('lift1', 'lift2old', 'lift3old', 'lift4old'): gens += [d for _, d in mine[fam]]
G = to_csr(gens); NG = G.shape[0]; del gens
log(f'generators: {NG} rows (std + lifts), nnz {G.nnz} ({time.time()-t0:.0f}s)', LOG)
# ---- e sh G (weight-4 proved rows) ----
B = bases()
g4 = list(B[4])
A3 = {k: pickle.load(open(T + f'/A3h4_frame_ds/validated_w{k}.pickle', 'rb'))['rows'] for k in (2, 3, 4)}
FR13 = [(2, 3), (3, 3), (3, 5), (3, 6), (4, 4), (4, 6), (4, 8), (4, 9), (4, 11), (4, 12), (4, 40), (4, 41), (4, 43)]
for k, i in FR13:
    for w in WORDS(4 - k):
        d = shv({tuple(x): c for x, c in A3[k][i]}, {w: 1})
        if d: g4.append(d)
eG = to_csr([shv(E, {w: F(c) for w, c in g.items()}) for g in g4])
log(f'e sh G: {len(g4)} weight-4 generators ({time.time()-t0:.0f}s)', LOG)
ESH = to_csr([shv(E, {w: 1}) for w in W4])          # e sh word, all 5184 words (the space I)
# ---- targets ----
OPEN = [4, 5, 7, 9, 10, 12, 14, 15, 16, 17, 52, 53, 54, 56, 58, 59, 61, 63, 64, 65, 66, 67, 68, 69, 70, 71, 72, 73, 74, 75, 87, 91, 95, 103, 104, 107, 113]
TARGETS = [(i, u) for i in OPEN for u in (3, 5)]
V5 = pickle.load(open(T + '/W5C1_certificate_scoping/validated_w5.pkl', 'rb'))
f5 = [{tuple(w): c for w, c in r} for r in V5['rows']]
cs = {(r['i'], r['u']): r for r in pickle.load(open(T + '/W5G2_frame_exact/cert_summary.pkl', 'rb'))['summary']}
fr234 = mine['frame234']
xs = []; vs = []
for (i, u) in TARGETS:
    v = actv(f5[i], u); vs.append(v)
    x = {w: F(c) for w, c in v.items()}
    for (fam, j, g), a in cs[(i, u)]['frame_terms']:
        assert g == 1
        Fj = f5[j] if fam == 'framew5' else fr234[j][1]
        for w, c in Fj.items(): x[w] = x.get(w, F(0)) - a * c
    xs.append({w: c for w, c in x.items() if c})
X = to_csr(xs)
# controls (must NOT be in the span)
ctl_names = ['v=u3.f4 itself (no frame terms)', 'v=u5.f113 itself', 'x(u3.f4) + unit vector', 'e sh (1,-1,-1,1)', 'random vector']
unit = {W5[12345]: 1}
ctl = [vs[0], vs[-1], {**xs[0], W5[12345]: xs[0].get(W5[12345], 0) + 1}, shv(E, {(1, -1, -1, 1): 1}),
       {w: int(c) for w, c in zip(W5, rng.integers(1, p, N5))}]
C = to_csr(ctl)
log(f'targets {len(TARGETS)} built ({time.time()-t0:.0f}s)', LOG)
# ---- random combinations ----
m = n + 64; cper = 4
rows_ = np.repeat(np.arange(NG), cper); tg = rng.integers(0, m, NG * cper); cf = rng.integers(1, p, NG * cper)
R = sps.csr_matrix((cf.astype(np.int64), (tg, rows_)), shape=(m, NG))
A = np.empty((m, n), np.float64)
for s in range(0, m, 2048):
    blk = (R[s:s + 2048] @ G); blk.data %= p
    A[s:s + 2048] = dense(blk)
del G, R
NR = 1200
def rcomb(M, k):
    Rr = sps.csr_matrix(rng.integers(0, p, (k, M.shape[0])).astype(np.int64) % 1024)   # small coefficients: no overflow
    out = Rr @ M; out.data %= p; return out
Tm = np.concatenate([dense(X), dense(C), dense(rcomb(eG, NR)), dense(rcomb(ESH, NR))])
log(f'M\' {m} x {n} dense, test rows {Tm.shape[0]} ({time.time()-t0:.0f}s)', LOG)
rk, Res = elim(A, Tm, p, logf=lambda s: log(s, LOG))
del A
nx, nc = len(TARGETS), len(ctl)
RX, RC, RE, RI = Res[:nx], Res[nx:nx + nc], Res[nx + nc:nx + nc + NR], Res[nx + nc + NR:]
log(f'rank of span(Lgen) in sector {SEC}: {rk}; codim {n - rk} ({time.time()-t0:.0f}s)', LOG)
# ---- quotient analysis on the non-pivot columns ----
nzc = np.flatnonzero(np.any(Res != 0, axis=0))
def rank_of(Mx):
    Mx = Mx[:, nzc].copy()
    if Mx.shape[0] == 0: return 0
    r, _ = elim(Mx, np.zeros((0, Mx.shape[1])), p); return r
rE = rank_of(RE); rI = rank_of(RI)
log(f'residue ranks: e sh G -> {rE}; I = e sh words(4) -> {rI} (of {NR} random combinations each)', LOG)
inL = [int(not np.any(RX[t])) for t in range(nx)]
inLE = []
for t in range(nx):
    inLE.append(int(rank_of(np.concatenate([RE, RX[t:t + 1]])) == rE))
log(f'targets x_t in span(Lgen): {sum(inL)}/{nx}; in span(Lgen) + e sh span(G): {sum(inLE)}/{nx}', LOG)
for t, (i, u) in enumerate(TARGETS):
    log(f'  u{u}.f{i}: in L: {inL[t]}, in L + e sh G: {inLE[t]}', LOG)
for c in range(nc):
    a = int(not np.any(RC[c])); b_ = int(rank_of(np.concatenate([RE, RC[c:c + 1]])) == rE)
    b2 = int(rank_of(np.concatenate([RI, RC[c:c + 1]])) == rI)
    log(f'  control {ctl_names[c]}: in L {a}, in L + e sh G {b_}, in L + I {b2}', LOG)
pickle.dump(dict(p=p, sec=SEC, n=n, rank=rk, rE=rE, rI=rI, inL=inL, inLE=inLE), open(HERE + f'/r02_{p}_{"p" if SEC == "+" else "m"}.pkl', 'wb'))
log(f'done ({time.time()-t0:.0f}s)', LOG)
