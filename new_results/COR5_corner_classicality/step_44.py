from fractions import Fraction as Fr
import json

# ---- Completeness proof for the {2,3}-unit equation x + y = 1 ----
# LEMMA (consecutive 3-smooth numbers): positive 3-smooth P,Q with P-Q=1 are
# (P,Q) in {(2,1),(3,2),(4,3),(9,8)}. Elementary proof (see result.md):
#   gcd(P,Q)=1 and both 3-smooth => {P,Q} = {2^a,3^b} or (2,1).
#   2^a - 3^b = 1: mod 3 => a even => (2^{a/2}-1)(2^{a/2}+1)=3^b => 2^{a/2}-1=1 => a=2,b=1.
#   3^b - 2^a = 1: a=1 => b=1; a>=2: mod 4 => b even => (3^{b/2}-1)(3^{b/2}+1)=2^a
#     => 3^{b/2}-1=2, 3^{b/2}+1=4 => b=2, a=3.
pairs = [(2,1),(3,2),(4,3),(9,8)]
# verify the two factorization claims exactly
assert all(2**a - 3**b == 1 for a, b in [(2,1)])
assert all(3**b - 2**a == 1 for b, a in [(1,1),(2,3)])

# REDUCTION: x + y = 1, x = e1*2^a1*3^b1, y = e2*2^a2*3^b2.
# Multiply by 2^{-min(a1,a2,0)} 3^{-min(b1,b2,0)}:  e1 2^A1 3^B1 + e2 2^A2 3^B2 = 2^M 3^N,
# exponents >= 0, min(A1,A2,M) = min(B1,B2,N) = 0.
# CLAIM: one of the three terms is +-1.  Proof by cases (printed):
print("""CLAIM: in e1*2^A1*3^B1 + e2*2^A2*3^B2 = 2^M*3^N (exponents >= 0,
min(A1,A2,M) = min(B1,B2,N) = 0), one term is +-1.
Case work:
* M = 0, N = 0: RHS = 1 is +-1. done.
* M = 0, N >= 1: min(B1,B2,N)=0 => B1=0 or B2=0; say B1=0, so term1 = +-2^A1.
  mod 2 of +-2^A1 = 3^N - e2*2^A2*3^B2 forces A2 = 0 (else RHS odd difference is even);
  then +-2^A1 +- 3^B2 = 3^N with B2, N >= 1 (B2=0 => term2 = +-1) => mod 3: +-2^A1 == 0. no.
* M >= 1: min(A1,A2,M)=0 => A1=0 or A2=0; say A1=0, term1 = +-3^B1, B1>=1 (else +-1).
  min(B1,B2,N)=0 => B2=0 or N=0.
  - N = 0: +-3^B1 + e2*2^A2*3^B2 = 2^M. A2 >= 1: mod 2: +-1 == 0. no.
    A2 = 0: term2 = +-3^B2 (B2>=1 else +-1): +-3^B1 +- 3^B2 = 2^M, mod 3: 0 == +-1. no.
  - N >= 1, B2 = 0: term2 = +-2^A2 (A2>=1 else +-1): +-3^B1 +- 2^A2 = 2^M 3^N,
    mod 2: +-1 == 0. no.
So a term is +-1: +-1 +- 2^A2 3^B2 = +-2^M 3^N, i.e. two 3-smooth numbers differ by 1.""")

# Generate all (x,y) from the lemma: +-1 + t = u (signs) with {t,u} consecutive 3-smooth (ordered,
# including 1 itself as the +-1 term and the 1+1=2 case), then x = (first term)/u etc.
# Simpler: enumerate all ordered triples (s1*t1, s2*t2, t3) with t1,t2,t3 in {1} U {terms from pairs},
# s1*t1 + s2*t2 = t3, then normalize x = s1*t1/t3, y = s2*t2/t3 and collect.
terms = set([Fr(1)])
for P, Q in pairs:
    terms.add(Fr(P)); terms.add(Fr(Q))
found = set()
for t1 in terms:
    for t2 in terms:
        for t3 in terms:
            for s1 in (1, -1):
                for s2 in (1, -1):
                    if s1*t1 + s2*t2 == t3:
                        x = Fr(s1)*t1/t3; y = Fr(s2)*t2/t3
                        found.add((x, y))
xs_found = sorted(set(x for x, y in found))
known = sorted(set(Fr(xs) for xs, fx, fy in json.load(open("sunit23_solutions.json"))))
print("solutions generated by the lemma:", len(xs_found))
print("solutions found by bounded search:", len(known))
print("EQUAL:", xs_found == known)
print()
print("Complete list of the 21 solutions x (with y = 1-x):")
print(", ".join(str(x) for x in xs_found))
