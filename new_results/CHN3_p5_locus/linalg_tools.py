"""Exact linear algebra tools: homogeneous poly interpolation and ideal membership, via flint."""
from fractions import Fraction as F
from itertools import combinations_with_replacement
import sympy as sp
from flint import fmpq_mat, fmpq

def monoms_homog(d, n):
    """all exponent tuples of total degree d in n vars, lex order."""
    out=[]
    def rec(rem, k, cur):
        if k==n-1:
            out.append(tuple(cur+[rem])); return
        for i in range(rem+1):
            rec(rem-i, k+1, cur+[i])
    rec(d,0,[])
    return out

def solve_linear(Arows, b):
    """Solve A x = b over Q. Arows: list of lists of Fraction (m eqs, n unknowns).
    Returns particular solution (list of Fraction) or None if inconsistent."""
    m=len(Arows); n=len(Arows[0])
    data=[]
    for row in Arows:
        for c in row:
            data.append(fmpq(c.numerator,c.denominator))
    for c in b:
        data.append(fmpq(0))  # placeholder, will build augmented separately
    # build augmented matrix [A|b]
    M=fmpq_mat(m, n+1, [fmpq(c.numerator,c.denominator) for row,bb in zip(Arows,b) for c in list(row)+[bb]])
    R, rank = M.rref()
    # check consistency: a row [0...0|1]
    for i in range(m):
        rowzero=all(R[i,j]==0 for j in range(n))
        if rowzero and R[i,n]!=0: return None
    # particular solution from rref: free vars = 0
    x=[F(0)]*n
    pivcol={}
    for i in range(m):
        lead=None
        for j in range(n):
            if R[i,j]!=0: lead=j; break
        if lead is not None:
            pivcol[lead]=i
    for j,i in pivcol.items():
        v=R[i,n]; x[j]=F(int(v.p),int(v.q))
    return x

def ideal_member(Fpoly, gens, vars5, deg_F):
    """Test F in (gens) for a complete-intersection ideal generated by homogeneous gens.
    gens: list of (sympy poly, its degree). Solve F = sum U_i g_i with U_i homogeneous.
    Returns dict of U_i (sympy) or None."""
    from common import sym_to_dict, dict_to_sym
    unknowns=[]  # (gen_index, monom)
    for gi,(g,dg) in enumerate(gens):
        dU=deg_F-dg
        if dU<0: continue
        for mon in monoms_homog(dU, len(vars5)):
            unknowns.append((gi,mon))
    n=len(unknowns)
    # equations: for each monomial of degree deg_F, coeff match
    eqs={}
    Fd=sym_to_dict(Fpoly, len(vars5))
    # build columns
    allmons=monoms_homog(deg_F, len(vars5))
    midx={m:i for i,m in enumerate(allmons)}
    rows=[[F(0)]*n for _ in allmons]
    for j,(gi,mon) in enumerate(unknowns):
        g,dg=gens[gi]
        gd=sym_to_dict(g, len(vars5))
        for gm,gc in gd.items():
            tot=tuple(gm[k]+mon[k] for k in range(len(vars5)))
            rows[midx[tot]][j]+=gc
    b=[Fd.get(m,F(0)) for m in allmons]
    sol=solve_linear(rows,b)
    if sol is None: return None
    out={}
    for gi in range(len(gens)):
        terms=[(mon,sol[j]) for j,(gj,mon) in enumerate(unknowns) if gj==gi and sol[j]!=0]
        if terms:
            out[gi]=dict_to_sym({m:c for m,c in terms}, len(vars5))
        else:
            out[gi]=sp.Integer(0)
    return out
