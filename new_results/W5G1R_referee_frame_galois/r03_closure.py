"""r03: (a) literal closure of W5C1's std family (all 94762 rows) under u = 3, 5, 7;
(b) provenance of the proved bases B1..B4 (regenerated from make_relations / labels, as Theorem W4R's verifier does);
(c) exact re-check of W5G1's stored lift decompositions u.b = sum t_i b_i + e sh y (own shuffle code)."""
from rcommon import *
import pickle, collections
from math import gcd, lcm
L = 'r03.log'
W5C1 = T + '/W5C1_certificate_scoping'
sys.path.insert(0, T + '/A3c_claude_elementary/Q')
import relations as rel
rel.log = lambda s: None
W5 = words(5); assert tuple(W5) == tuple(rel.words(5)), 'word order differs'
def prim(d):
    d = {w: F(c) for w, c in d.items() if c}
    den = lcm(*[c.denominator for c in d.values()])
    it = sorted((w, int(c * den)) for w, c in d.items())
    g = 0
    for _, a in it: g = gcd(g, abs(a))
    if it[0][1] < 0: g = -g
    return tuple((w, a // g) for w, a in it)
# (a)
std = pickle.load(open(W5C1 + '/rels_std.pkl', 'rb'))
S = {prim({W5[i]: c for i, c in r}) for _, r in std}
miss = collections.Counter()
for _, r in std:
    d = {W5[i]: c for i, c in r}
    for u in (3, 5, 7):
        if prim(actv(d, u)) not in S: miss[u] += 1
log(f'(a) std rows {len(std)} (unique {len(S)}); u-images NOT literally in std: {dict(miss) or "none"}', L)
del std, S
# (b) bases
B = {}
lower = {}
for n in (1, 2, 3):
    cols, rows, sel = pickle.load(open(T + f'/A3c_claude_elementary/Q/weight{n}.pickle', 'rb'))
    gen, _ = rel.make_relations(n, lower)
    gs = set(gen)
    ok = all(r in gs for r in sel)
    fams = collections.Counter()
    log(f'(b) weight {n}: selected base rows {len(sel)}, all regenerated by make_relations: {ok}', L)
    lower[n] = sel
    B[n] = [{tuple(w): F(c) for w, c in r} for r in sel]
T0 = pickle.load(open(T + '/A3h_weight4_target/w4_systems_T.pkl', 'rb'))['T0']
Sidx = pickle.load(open(T + '/A3h5_exact_certificate/stage2_rows_S.pkl', 'rb'))['S']
std4, _ = rel.make_relations(4, {})
fam = collections.Counter(); bad = 0
for i in Sidx:
    lab, row = T0[i]
    d = {tuple(w): F(c) for w, (q, c) in row}
    assert all(q == 0 for w, (q, c) in row)
    if lab[0] == 'std': ref = std4[lab[1]]
    else:
        n = {'lift1': 1, 'lift2old': 2, 'lift3old': 3}[lab[0]]
        ref = rel.primitive(rel.mul(dict(lower[n][lab[1]]), {tuple(lab[2]): 1}))
    fam[lab[0]] += 1
    if prim(d) != prim(dict(ref)): bad += 1
log(f'(b) weight 4: B4 = T0[S], {len(Sidx)} rows by family {dict(fam)}; mismatches against regeneration: {bad}', L)
B[4] = [{tuple(w): F(c) for w, (q, c) in T0[i][1]} for i in Sidx]
# (c)
DEC = pickle.load(open(T + '/W5G1_frame_galois/lift_decomp.pkl', 'rb'))
E = {(2,): F(1), (6,): F(-1)}
nz = []
bad = 0
for (n, j, u), (t, y) in DEC.items():
    lhs = actv(B[n][j], u)
    rhs = {}
    for i, ti in t.items():
        for w, c in B[n][i].items(): rhs[w] = rhs.get(w, 0) + ti * c
    if y:
        nz.append((n, j, u, dict(y)))
        yv = {(w if isinstance(w, tuple) else ()): c for w, c in y.items()}
        for w, c in shv(E, yv).items(): rhs[w] = rhs.get(w, 0) + c
    if any(lhs.get(w, 0) != rhs.get(w, 0) for w in set(lhs) | set(rhs)): bad += 1
log(f'(c) {len(DEC)} stored decompositions; exact failures: {bad}; nonzero e-part: {[(n, j, u, y) for n, j, u, y in nz]}', L)
pickle.dump(B, open(HERE + '/r03_bases.pkl', 'wb'))
