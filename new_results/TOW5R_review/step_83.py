code = '''"""step_15 (TOW5R): FRESH rho cells at degrees 41, 42 (beyond TOW5's data range d <= 40),
generated by my own run of the copied trunc_engine (TOWN1's engine, byte-verified).
Check rho(9)/rho(0) == a_9 and rho(10)/rho(0) == a_10 at every key.
"""
import os, sys, time
from fractions import Fraction as Fr
_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, _HERE + '/tow5_copy')
import sympy as sp
import trunc_engine as te
import tow5lib as T5
d, m = T5.d, T5.m
t0 = time.time()
def gm(a, b): return (a[0]*b[0]-a[1]*b[1], a[0]*b[1]+a[1]*b[0])
def gd(a, b):
    den = b[0]**2+b[1]**2; return ((a[0]*b[0]+a[1]*b[1])/den, (a[1]*b[0]-a[0]*b[1])/den)
def qsi_div_q(x, y):
    A = (x.p0, x.p2); B = (x.p1, x.p3); C = (y.p0, y.p2); D = (y.p1, y.p3)
    C2 = (gm(C, C)[0]-2*gm(D, D)[0], gm(C, C)[1]-2*gm(D, D)[1])
    nA = (gm(A, C)[0]-2*gm(B, D)[0], gm(A, C)[1]-2*gm(B, D)[1])
    nB = (gm(B, C)[0]-gm(A, D)[0], gm(B, C)[1]-gm(A, D)[1])
    return (gd(nA, C2), gd(nB, C2))
S2 = te.stirling_table(43)
bad = n = 0
for dd in [41, 42]:
    RL = te.rho_level(dd, 10, S2)
    a9 = T5.arho(9); a10 = T5.arho(10)
    for key, vals in RL.items():
        for delta, aa in [(9, a9), (10, a10)]:
            rv = qsi_div_q(vals[delta], vals[0])
            cv = sp.expand(aa.subs({d: dd, m: key[0]}))
            exp = (Fr(sp.re(cv)), Fr(sp.im(cv)))
            n += 1
            if rv[1] != (Fr(0), Fr(0)) or rv[0] != exp: bad += 1
    print(f'd={dd}: fresh engine rho cells checked ({round(time.time()-t0,1)}s)', flush=True)
print(f'STEP_15 VERDICT: fresh d=41,42 engine cells: {n} checks, bad = {bad}', flush=True)
assert bad == 0
'''
