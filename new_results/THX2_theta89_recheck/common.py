def e_table(m, r):
    return smul(spow(gd2, m), Eser)[r]

def Dtilde_vec(n, m):
    """D~_{n,m} = 2 sum_{j=1}^{n-1-2m} e_{m,n-1-j} I_{n-1-j,j}/j!,  I_{r,j} = j! r! G(0^{r+1}(-1)^j)"""
    out = {}
    for j in range(1, n-2*m):
        r = n-1-j
        e = e_table(m, r)
        if e == 0: continue
        w = (0,)*(r+1)+(-1,)*j
        out[w] = out.get(w, F(0)) + 2*e*fact(r)
    return {k: v for k, v in out.items() if v}

