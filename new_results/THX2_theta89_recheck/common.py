NORD = 14
def smul(a, b):
    c = [F(0)]*NORD
    for i, x in enumerate(a):
        if x:
            for j, y in enumerate(b):
                if i+j < NORD: c[i+j] += x*y
    return c
def spow(a, k):
    r = [F(1)]+[F(0)]*(NORD-1)
    for _ in range(k): r = smul(r, a)
    return r
def compose_poly(coefs, y):  # sum coefs[k] y^k, y has zero const term
    r = [F(0)]*NORD; p = [F(1)]+[F(0)]*(NORD-1)
    for c in coefs:
        r = [r[i]+c*p[i] for i in range(NORD)]; p = smul(p, y)
    return r
def binom_gen(alpha, k):
    r = F(1)
    for i in range(k): r = r*(alpha-i)/(i+1)
    return r
fact = math.factorial
expx2 = [F(1, 2**k*fact(k)) for k in range(NORD)]
cosh = [F(1, fact(k)) if k % 2 == 0 else F(0) for k in range(NORD)]
sinh = [F(1, fact(k)) if k % 2 == 1 else F(0) for k in range(NORD)]
ycosh = cosh[:]; ycosh[0] = F(0)
sech32 = compose_poly([binom_gen(F(-3, 2), k) for k in range(NORD)], ycosh)   # cosh^{-3/2}
Eser = smul(expx2, sech32)                                                    # 2^{3/2} H(x)
gd = compose_poly([F((-1)**k, 2*k+1) if True else 0 for k in range(NORD)], [F(0)]*NORD)  # placeholder
# atan(sinh x) = sum (-1)^k sinh^(2k+1)/(2k+1)
gd = [F(0)]*NORD; sp_ = sinh[:]
