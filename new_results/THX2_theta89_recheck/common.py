def verify_certificate(h, V, data, B, crosscheck=True, label=''):
    """exact check  sum_i h_i R_{B[i]} == V  with R regenerated by my own code from the (family, tag) labels.
       Also (crosscheck) compare my regenerated row with the stored row."""
    assert len(h) == len(B)
    acc = {}      # word -> {den: numerator-sum}
    mism = 0
    for i, hi in enumerate(h):
        fam, tag, stored = data[B[i]]
        if hi == 0: continue
        row = my_relation(fam, tag)
        if crosscheck:
            if {k: F(a, b) for k, (a, b) in stored.items() if a} != {k: F(x) for k, x in row.items()}: mism += 1
        d = hi.denominator; n = hi.numerator
        for k, c in row.items():
            dd = acc.setdefault(k, {}); dd[d] = dd.get(d, 0) + n*c
    ok = True
    words = set(acc) | set(V)
    for k in words:
        tot = F(0)
        for d, nsum in acc.get(k, {}).items(): tot += F(nsum, d)
        if tot != V.get(k, 0): ok = False; break
    return ok, mism

def norm_h(h, n):
    """certificate data may be a list or a {index: value} dict (values may be flint.fmpq); return list of Fraction"""
    if isinstance(h, dict):
        out = [F(0)]*n
        for i, x in h.items(): out[i] = F(str(x))
        return out
    return [x if isinstance(x, F) else F(str(x)) for x in h]
