for k, W in [(1, W1), (2, W2), (3, W3), (4, W4)]:
    print(f"Wt{k}: |closed form - printed value| = {mp.nstr(abs(W - mp.mpf(val[k])), 3)}")
print("Wt5 remainder R = Wt5 - Wt5_log =", mp.nstr(mp.mpf(val[5]) - W5log, 30))
print("Li3(1/phi^2) Lewin form check:", mp.nstr(Li(3, phi**-2) - (Q(4)/5*z3 - Q(2)/15*mp.pi**2*L + Q(2)/3*L**3), 3))
