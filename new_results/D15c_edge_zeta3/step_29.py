
lines = []
lines.append("import mpmath as mp")
lines.append("mp.mp.dps = 100")
lines.append("import sympy as sp, json")
lines.append("from poly_coeffs import make_coeffs, regular_zeros")
lines.append("import sym_G")
lines.append("G21s,G12s,syms = sym_G.build()")
lines.append("order = [syms[k] for k in ['s0','s1','c0','c1','tau1','tau2','tau3','gam1','gam2','gam3','S0','Sc','lS0']]")
lines.append("f21 = sp.lambdify(order,G21s,'mpmath'); f12 = sp.lambdify(order,G12s,'mpmath')")
lines.append("def symvals(m,th):")
lines.append("    zeros=regular_zeros(m); sr=[mp.sin(th-b) for b in zeros]")
lines.append("    sv=[abs(x) for x in sr]; cv=[mp.cos(th-b)*mp.sign(x) for b,x in zip(zeros,sr)]")
lines.append("    lv=[mp.log(s) for s in sv]; N=range(1,m-1)")
lines.append("    s0=sv[0];c0=cv[0];s1=sv[m-1];c1=cv[m-1]")
lines.append("    tau=[mp.fsum([sv[i]*lv[i]**k for i in N]) for k in (1,2,3)]")
lines.append("    gam=[mp.fsum([cv[i]*(lv[i]**k+k*lv[i]**(k-1)) for i in N]) for k in (1,2,3)]")
lines.append("    S0=mp.fsum(sv);Sc=mp.fsum(cv)")
lines.append("    return [s0,s1,c0,c1,tau[0],tau[1],tau[2],gam[0],gam[1],gam[2],S0,Sc,mp.log(S0)]")
lines.append("print('dps:',mp.mp.dps)")
lines.append("z3=mp.zeta(3)")
lines.append("vals=json.load(open('vals_m2_8_200.json'))")
lines.append("def Cm(m):")
lines.append("    h=mp.pi/(2*m); s=mp.sin(h); return 48*m*s**4*mp.cos(h)*(3*s**2-1)")
lines.append("out={}")
lines.append("for m in range(2,9):")
lines.append("    A=mp.pi/m")
lines.append("    coeffs=make_coeffs(regular_zeros(m),[1]*m,[0]*m)")
lines.append("    fullint=mp.quad(lambda th:coeffs(th)[3],[0,A],method='tanh-sinh')")
lines.append("    crossG=mp.quad(lambda th: f21(*symvals(m,th))+f12(*symvals(m,th)),[0,A],method='tanh-sinh')")
lines.append("    P3_full = 12*m*fullint")
lines.append("    P3v = mp.mpf(vals[str(m)][3])")
lines.append("    rem_m = fullint - 2*z3*crossG")
lines.append("    out[m]=dict(fullint=mp.nstr(fullint,90), crossG=mp.nstr(crossG,90), rem=mp.nstr(rem_m,90))")
lines.append("    print('m=%d: crossG-C_m/(24m) resid=%s'%(m, mp.nstr(abs(crossG-Cm(m)/(24*m)),3)))")
lines.append("    print('    12m*fullint - vals P3 resid=%s'%mp.nstr(abs(P3_full-P3v),3))")
lines.append("    print('    rem_m=%s'%mp.nstr(rem_m,28))")
lines.append("json.dump(out,open('rem_m.json','w'))")
with open('step_14_rem.py','w') as f:
    f.write("\n".join(lines)+"\n")
import subprocess
r=subprocess.run(['./.venv/bin/python','step_14_rem.py'],capture_output=True,text=True,timeout=900)
print(r.stdout); print(r.stderr[-1500:] if r.stderr else "")
