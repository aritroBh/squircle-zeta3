
settle = []
settle.append("import mpmath as mp")
settle.append("mp.mp.dps=80")
settle.append("import sympy as sp, pickle")
settle.append("from poly_coeffs import regular_zeros")
settle.append("import sym_G")
settle.append("z3=mp.zeta(3); pi=mp.pi")
settle.append("# 1) plain single-corner log^3 sine integral")
settle.append("I=mp.quad(lambda th: mp.log(mp.sin(th))**3,[0,mp.pi/2],method='tanh-sinh')")
settle.append("print('int_0^{pi/2} log^3(sin th) dth =',mp.nstr(I,30))")
settle.append("basis=[z3,pi**3,pi**2*mp.log(2),pi*mp.log(2)**2,mp.log(2)**3,pi*mp.catalan]")
settle.append("bn=['z3','pi^3','pi^2log2','pi*log2^2','log2^3','pi*G']")
settle.append("rel=mp.pslq(mp.matrix([I]+basis),tol=mp.mpf('1e-70'),maxcoeff=100000)")
settle.append("print('pslq:',rel)")
settle.append("if rel is not None and rel[0]!=0:")
settle.append("    print('  => I = ', -sum(mp.mpf(rel[k+1])*basis[k] for k in range(len(basis)))/rel[0])")
settle.append("    print('  z3 coeff =', mp.nstr(-mp.mpf(rel[1])/rel[0],10))")
settle.append("# 2) our c30*l0^3 for m=2")
settle.append("data=pickle.load(open('allcoeffs.pkl','rb'))")
settle.append("coeffs={k:sp.sympify(v) for k,v in data.items()}")
settle.append("_,_,syms=sym_G.build()")
settle.append("order=[syms[k] for k in ['s0','s1','c0','c1','tau1','tau2','tau3','gam1','gam2','gam3','S0','Sc','lS0']]")
settle.append("lam={k:sp.lambdify(order,coeffs[k],'mpmath') for k in coeffs}")
settle.append("def symvals(m,th):")
settle.append("    zeros=regular_zeros(m);sr=[mp.sin(th-b) for b in zeros]")
settle.append("    sv=[abs(x) for x in sr];cv=[mp.cos(th-b)*mp.sign(x) for b,x in zip(zeros,sr)]")
settle.append("    lv=[mp.log(s) for s in sv];N=range(1,m-1)")
settle.append("    tau=[mp.fsum([sv[i]*lv[i]**k for i in N]) for k in (1,2,3)]")
settle.append("    gam=[mp.fsum([cv[i]*(lv[i]**k+k*lv[i]**(k-1)) for i in N]) for k in (1,2,3)]")
settle.append("    S0=mp.fsum(sv);Sc=mp.fsum(cv)")
settle.append("    return [sv[0],sv[m-1],cv[0],cv[m-1],tau[0],tau[1],tau[2],gam[0],gam[1],gam[2],S0,Sc,mp.log(S0)],lv[0],lv[1]")
settle.append("for m in [2]:")
settle.append("    A=mp.pi/m")
settle.append("    J=mp.quad(lambda th: lam[(3,0)](*symvals(m,th)[0])*symvals(m,th)[1]**3,[0,A],method='tanh-sinh')")
settle.append("    print('m=2 int c30*l0^3 =',mp.nstr(J,30))")
settle.append("    rel=mp.pslq(mp.matrix([J]+basis),tol=mp.mpf('1e-68'),maxcoeff=100000)")
settle.append("    print('   pslq:',rel)")
settle.append("    if rel is not None and rel[0]!=0: print('   z3 coeff=',mp.nstr(-mp.mpf(rel[1])/rel[0],10))")
with open('step_15_settle.py','w') as f: f.write("\n".join(settle)+"\n")
import subprocess
r=subprocess.run(['./.venv/bin/python','step_15_settle.py'],capture_output=True,text=True,timeout=300)
print(r.stdout); print(r.stderr[-1500:] if r.stderr else "")
